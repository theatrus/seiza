fn stretch(model: StretchModel, color_strategy: ColorStrategy) -> Vec<f64> {
    let stack = StretchStack::new(vec![StretchConfig {
        model,
        color_strategy,
        max_analysis_samples: seiza_stretch::DEFAULT_SAMPLE_ANALYSIS_SAMPLES,
    }])
    .unwrap();
    let output = stack
        .apply_f32_image(&field(), ImageShape::new(WIDTH, HEIGHT, 3))
        .unwrap();
    summary(&output.data)
}

/// Uniform noise in `[-amplitude, amplitude)` from a hash of the sample.
fn noise(index: usize, amplitude: f32) -> f32 {
    let mut hash = (index as u64).wrapping_mul(0x9e37_79b9_7f4a_7c15);
    hash ^= hash >> 31;
    hash = hash.wrapping_mul(0x94d0_49bb_1331_11eb);
    hash ^= hash >> 29;
    ((hash >> 40) as f32 / (1 << 24) as f32 * 2.0 - 1.0) * amplitude
}

/// A linear colour field on a 0 to 1 scale: a faint tinted sky with a
/// gradient, a soft nebula, and thirty stars from a small integer generator.
fn field() -> Vec<f32> {
    field_sized(WIDTH, HEIGHT)
}

fn field_sized(width: usize, height: usize) -> Vec<f32> {
    let mut state = 0x2545_f491_u32;
    let mut next = || {
        state = state.wrapping_mul(1_664_525).wrapping_add(1_013_904_223);
        (state >> 8) as f32 / (1 << 24) as f32
    };
    let stars = (0..30)
        .map(|_| {
            let x = next() * width as f32;
            let y = next() * height as f32;
            (x, y, 0.05 + next() * 0.9, 0.6 + next() * 0.4)
        })
        .collect::<Vec<_>>();
    const SKY: [f32; 3] = [0.050, 0.045, 0.040];
    const NEBULA: [f32; 3] = [0.030, 0.010, 0.020];
    let mut data = Vec::with_capacity(width * height * 3);
    for y in 0..height {
        for x in 0..width {
            let (fx, fy) = (x as f32, y as f32);
            let (nx, ny) = (fx - 90.0, fy - 60.0);
            let nebula = (-(nx * nx + ny * ny) / 1_800.0).exp();
            for channel in 0..3 {
                let mut value = SKY[channel] + 0.0001 * fx + NEBULA[channel] * nebula;
                for &(star_x, star_y, flux, warmth) in &stars {
                    let (dx, dy) = (fx - star_x, fy - star_y);
                    let tint = [1.0, 0.9, 1.6 - warmth][channel];
                    value += flux * tint * (-(dx * dx + dy * dy) / 3.0).exp();
                }
                let index = data.len();
                data.push((value + noise(index, 0.004)).clamp(0.0, 1.0));
            }
        }
    }
    data
}

/// Each channel's mean, root mean square and maximum, then the samples on a
/// 5 by 5 grid of interior points.
fn summary(data: &[f32]) -> Vec<f64> {
    summary_sized(data, WIDTH, HEIGHT)
}

fn summary_sized(data: &[f32], width: usize, height: usize) -> Vec<f64> {
    let mut values = Vec::new();
    for channel in 0..3 {
        let (mut sum, mut squares, mut maximum) = (0.0_f64, 0.0_f64, f64::MIN);
        for &sample in data.iter().skip(channel).step_by(3) {
            let sample = f64::from(sample);
            sum += sample;
            squares += sample * sample;
            maximum = maximum.max(sample);
        }
        let count = (width * height) as f64;
        values.extend([sum / count, (squares / count).sqrt(), maximum]);
    }
    for row in 0..5 {
        for column in 0..5 {
            let x = 8 + column * (width - 16) / 4;
            let y = 8 + row * (height - 16) / 4;
            for channel in 0..3 {
                values.push(f64::from(data[(y * width + x) * 3 + channel]));
            }
        }
    }
    values
}

fn compare(case: &str, actual: &[f64], expected: &[f64]) -> Option<String> {
    let same = actual.len() == expected.len()
        && actual.iter().zip(expected).all(|(actual, expected)| {
            (actual - expected).abs() <= TOLERANCE * expected.abs().max(1.0)
        });
    (!same).then(|| {
        let recorded = actual
            .iter()
            .map(|value| format!("{value:.7e}"))
            .collect::<Vec<_>>()
            .join(", ");
        format!("\"{case}\" => &[{recorded}],")
    })
}
